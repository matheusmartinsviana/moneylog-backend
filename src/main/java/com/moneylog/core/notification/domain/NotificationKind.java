package com.moneylog.core.notification.domain;

public enum NotificationKind {
    INVOICE_DUE,
    DEBT_COLLECT,
    DEBT_PAYABLE_DUE,
    RECURRENCE_PENDING,
    COMMITTED_NEXT_MONTH,
    DAILY_SUMMARY,
    REMINDER,
    GOAL_DEADLINE,
    GROUPED,
    INVOICE_DUE_AUTODEBIT_OFF,
    NEGATIVE_MONTH_PROJECTED,
    NEW_DEBT_BEFORE_FINANCING,
    CARD_CASH_OUT_COST,
    SUBSCRIPTION_OVERLAP,
    SUBSCRIPTION_UNUSED,
    WEEKLY_CHARGE,
    THIRD_PARTY_OVERDUE,
    BALANCE_BELOW_REAL_ESTATE,
    DOCUMENT_DIVERGENCE;

    public boolean configurable() {
        return this != GROUPED && this != DAILY_SUMMARY && this != REMINDER;
    }
}
